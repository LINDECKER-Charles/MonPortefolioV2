const PAR_ID: ReadonlyMap<string, EntreeVisuel> = new Map(VISUELS.map((v) => [v.id, v]));

/** L’entrée d’un identifiant, ou `undefined` s’il n’existe pas. */
export function visuelParId(id: string): EntreeVisuel | undefined {
  return PAR_ID.get(id);
}

/**
 * Fichiers qu’un emplacement attend : le sien, ou ceux des emplacements dont
 * il reprend le fichier. Vide pour une figure codée sans composant existant.
 */
export function fichiersAttendus(visuel: EntreeVisuel): string[] {
  if (visuel.fichier) return [visuel.fichier];
  return (visuel.reprend ?? []).flatMap((id) => {
    const cible = PAR_ID.get(id);
    return cible ? fichiersAttendus(cible) : [];
  });
}

