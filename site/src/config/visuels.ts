/**
 * Registre des visuels de la refonte : chaque emplacement de l’inventaire
 * (cahier des charges, § 6), de l’identité aux états d’erreur, avec les
 * captures à faire (§ 6.12).
 *
 * Chaque emplacement du site est posé par `<Visuel id="…" />`
 * (`components/ui/Visuel.astro`), qui lit ce registre : il affiche l’image
 * quand le fichier attendu existe, sinon un cadre hachuré au bon ratio avec
 * l’identifiant, le sujet, la composition et le format. `npm run visuels` liste
 * ce qui manque (`-- --verifier` contrôle aussi les fichiers livrés) ;
 * `npm run visuels:doc` régénère `docs/visuels-a-generer.md`, la commande de
 * production des images.
 *
 * Ce fichier ne contient que de la syntaxe effaçable (pas d’enum) : les outils
 * Node (`tools/visuels-manquants.mjs`, `tools/generer-visuels.mjs`,
 * `tools/rendre-visuels.mjs`) l’importent tel quel.
 *
 * Champs :
 *   - `methode` : IMG image générée · SVG dessin vectoriel écrit à la main ·
 *     FIG figure codée depuis des données sourcées, jamais générée · CAP
 *     capture réelle · PHO photo réelle · OG image de partage composée en HTML
 *     puis rendue en PNG.
 *   - `priorite` : `socle` posé sur une page et nécessaire au lancement ;
 *     `elargi` non posé, enrichit et peut suivre. Une entrée posée est
 *     toujours « socle » (tests/unit/visuels.test.ts le vérifie).
 *   - `pose` : fichiers de `src/` qui posent l’entrée (page, composant ou
 *     configuration qui l’appelle) ; `null` quand aucune page ne l’attend, avec
 *     la raison dans `raisonNonPose`.
 *   - `composition` : la scène seule, à traduire dans le prompt ; `cadrage` :
 *     bandes sûres, recadrages et tailles d’affichage, pour vérifier l’image.
 *   - `lumiere` : position de la lanterne en % de la largeur et de la hauteur,
 *     contrainte dure des scènes animées (la lumière du site part de ce point).
 *   - `calques` et `fond` : ce que porte chaque couleur de clé d’une image
 *     générée (encre, aplat, lumière ; « Couleurs de clé » dans la commande),
 *     et si le fond reste transparent.
 *   - `alt` : texte alternatif prévu, qui décrit l’image ; chaîne vide pour un
 *     visuel décoratif.
 *   - `fichier` : chemin attendu, relatif à `site/` ; pour une figure codée, son
 *     composant ; `null` pour un emplacement qui reprend le fichier d’un autre
 *     (`reprend`) ou qui en attend plusieurs (`declinaisons`).
 *   - `pieces` : identifiants des pièces d’un fichier SVG (`<symbol id>` d’un
 *     sprite, ou classes de calques d’un dessin animé).
 *   - `sujetNeutre` : sujet sans nom de marque, à donner au générateur d’image
 *     quand le sujet en nomme une (règle 1 de la commande).
 *   - `auteur` : `charles` quand lui seul peut produire le fichier ; sinon Codex
 *     pour une image générée, l’équipe pour le reste.
 *
 * Famille de style (règle 5 de la commande) : celle de la direction
 * « Lanterne », retenue le 13 octobre 2026 (design/refonte/c-lanterne/README.md).
 * Gravure en réserve au trait économe, la lanterne seule source de lumière de
 * la scène. Chaque image générée a deux masters en trois couleurs de clé
 * (encre, aplat, lumière), dessinés au même cadrage au pixel près : le jour,
 * puis la nuit en édition depuis le jour (règle 6, décision du 13 octobre
 * 2026). `npm run visuels:rendre <ID>` les rend aux couleurs des jetons
 * (`RENDUS`). Aucune propriété intellectuelle de tiers, jamais le visage de
 * Charles, aucun texte dans l’image.
 *
 * Nommage : `<ID>_<largeur>x<hauteur>.webp` pour une image (le rendu de jour)
 * et `<ID>_<largeur>x<hauteur>.nuit.webp` pour son rendu de nuit, depuis les
 * masters `design/assets/visuels/<série>/<ID>.png` et `<ID>.nuit.png` ;
 * `<ID>.svg` pour un dessin vectoriel, `public/og/<ID>_1200x630.png` pour une
 * image de partage.
 */

export type MethodeVisuel = 'IMG' | 'SVG' | 'FIG' | 'CAP' | 'PHO' | 'OG';
export type PrioriteVisuel = 'socle' | 'elargi';
export type SerieVisuel =
  | 'global'
  | 'accueil'
  | 'projets'
  | 'pvz-fusion'
  | 'league-of-database'
  | 'omnicard'
  | 'bloodborne'
  | 'gup'
  | 'parcours'
  | 'contact'
  | 'blog'
  | 'etats';

/** Ce que porte chaque couleur de clé d’une image générée (règle 6). */
export interface CalquesVisuel {
  encre: string;
  aplat: string;
  lumiere: string;
}

/** Un fichier d’un emplacement qui en attend plusieurs (images de partage par page, posters…). */
export interface DeclinaisonVisuel {
  nom: string;
  fichier: string;
  alt: string;
}

export interface EntreeVisuel {
  /** Identifiant de l’inventaire : GLO-01, ACC-03, PVZ-F1, PVZ-C1… */
  id: string;
  /** Série de rangement des fichiers (`src/assets/visuels/<série>/`). */
  serie: SerieVisuel;
  /** Route de la page, ou `global` pour un élément de toutes les pages. */
  page: string;
  /** Où le visuel se pose dans la page (contexte, jamais dans un prompt). */
  emplacement: string;
  sujet: string;
  /** Sujet sans nom de marque, quand `sujet` en nomme une. */
  sujetNeutre?: string;
  /** La scène seule, à traduire dans le prompt. */
  composition: string;
  /** Bandes sûres, recadrages et tailles d’affichage, pour vérifier l’image. */
  cadrage?: string;
  /** Position de la lanterne, en % de la largeur et de la hauteur (scènes animées). */
  lumiere?: readonly [number, number];
  /** Ce que porte chaque couleur de clé (images générées). */
  calques?: CalquesVisuel;
  /** Fond transparent, ou rempli de l’aplat (images générées). */
  fond?: 'transparent' | 'aplat';
  /** Format et ratio, tels que l’inventaire les écrit. */
  format: string;
  /** Ratio de l’image au format CSS `aspect-ratio` ; `null` s’il est libre. */
  ratio: string | null;
  /** Ratio du recadrage mobile, quand il diffère. */
  ratioMobile?: string;
  largeur?: number;
  hauteur?: number;
  methode: MethodeVisuel;
  priorite: PrioriteVisuel;
  /** Fichiers de `src/` qui posent l’entrée ; `null` si aucune page ne l’attend. */
  pose: readonly string[] | null;
  /** Pourquoi l’entrée n’est pas posée (obligatoire quand `pose` est `null`). */
  raisonNonPose?: string;
  /** `charles` quand lui seul peut produire le fichier. */
  auteur?: 'charles';
  /** Texte alternatif prévu ; vide pour un visuel décoratif. */
  alt: string;
  /** Fichier attendu, relatif à `site/` ; composant d’une figure codée. */
  fichier: string | null;
  /** Emplacements dont ce visuel réutilise le fichier. */
  reprend?: readonly string[];
  /** Nombre d’éléments du lot (pictos d’une même planche, déclinaisons…). */
  lot?: number;
  /** Pièces d’un fichier SVG : `<symbol id>` d’un sprite, ou classes de calques. */
  pieces?: readonly string[];
  /** Fichiers d’un emplacement qui en attend plusieurs. */
  declinaisons?: readonly DeclinaisonVisuel[];
  note?: string;
}

