/**
 * Registre des visuels de la refonte : les 124 emplacements de l’inventaire
 * (cahier des charges, § 6), de l’identité aux états d’erreur.
 *
 * Chaque emplacement du site est posé par `<Visuel id="…" />`
 * (`components/ui/Visuel.astro`), qui lit ce registre : il affiche l’image
 * quand le fichier attendu existe, sinon un cadre hachuré au bon ratio avec
 * l’identifiant, le sujet, la composition et le format. `npm run visuels` liste ce qui manque ;
 * `npm run visuels:doc` régénère `docs/visuels-a-generer.md`, la commande de
 * production des images.
 *
 * Ce fichier ne contient que de la syntaxe effaçable (pas d’enum) : les outils
 * Node (`tools/visuels-manquants.mjs`, `tools/generer-visuels.mjs`) l’importent
 * tel quel.
 *
 * Champs :
 *   - `methode` : IMG image générée · SVG dessin vectoriel écrit à la main ·
 *     FIG figure codée depuis des données sourcées, jamais générée · CAP
 *     capture réelle · PHO photo réelle · OG image de partage composée en HTML
 *     puis rendue en PNG.
 *   - `priorite` : `socle` nécessaire au lancement de la refonte, `elargi`
 *     enrichit et peut suivre.
 *   - `alt` : texte alternatif prévu ; chaîne vide pour un visuel décoratif.
 *   - `fichier` : chemin attendu, relatif à `site/` ; `null` pour une figure
 *     codée (pas d’image) ou un emplacement qui reprend le fichier d’un autre
 *     (`reprend`).
 *   - `sujetNeutre` : sujet sans nom de marque, à donner au générateur d’image
 *     quand le sujet en nomme une (règle 1 de la commande).
 *
 * Famille de style (règle 5 de la commande) : celle de la direction
 * « Lanterne », retenue le 13 octobre 2026 (design/refonte/c-lanterne/README.md).
 * Gravure en réserve : trait clair sur fond sombre la nuit, inversé le jour ;
 * deux ou trois aplats francs et séparables (encre, aplat, lumière), recolorés
 * par les jetons du site ; la lanterne est la seule source de lumière de la
 * scène. Aucune propriété intellectuelle de tiers, jamais le visage de
 * Charles, aucun texte dans l’image.
 *
 * Nommage : `<ID>_<largeur>x<hauteur>.webp` pour une image, `<ID>.svg` pour un
 * dessin vectoriel, `public/og/<ID>_1200x630.png` pour une image de partage.
 * Taille non précisée par l’inventaire : largeur de 1 600 px ; 1 800 px pour un
 * 3:2 ou un ratio d’au moins 5:2 ; 2 100 px pour un 21:9 ; hauteur de 1 200 px
 * pour un carré ou un portrait.
 */

export type MethodeVisuel = 'IMG' | 'SVG' | 'FIG' | 'CAP' | 'PHO' | 'OG';
export type PrioriteVisuel = 'socle' | 'elargi';
export type SerieVisuel =
  | 'global'
  | 'accueil'
  | 'projets'
  | 'pvz-fusion'
  | 'league-of-database'
  | 'omnicard'
  | 'bloodborne'
  | 'gup'
  | 'parcours'
  | 'contact'
  | 'blog'
  | 'etats';

export interface EntreeVisuel {
  /** Identifiant de l’inventaire : GLO-01, ACC-03, PVZ-F1… */
  id: string;
  /** Série de rangement des fichiers (`src/assets/visuels/<série>/`). */
  serie: SerieVisuel;
  /** Route de la page, ou `global` pour un élément de toutes les pages. */
  page: string;
  /** Où le visuel se pose dans la page. */
  emplacement: string;
  sujet: string;
  /** Sujet sans nom de marque, quand `sujet` en nomme une. */
  sujetNeutre?: string;
  composition: string;
  /** Format et ratio, tels que l’inventaire les écrit. */
  format: string;
  /** Ratio de l’image au format CSS `aspect-ratio` ; `null` s’il est libre. */
  ratio: string | null;
  /** Ratio du recadrage mobile, quand il diffère. */
  ratioMobile?: string;
  largeur?: number;
  hauteur?: number;
  methode: MethodeVisuel;
  priorite: PrioriteVisuel;
  /** Texte alternatif prévu ; vide pour un visuel décoratif. */
  alt: string;
  /** Fichier attendu, relatif à `site/`. */
  fichier: string | null;
  /** Emplacements dont ce visuel réutilise le fichier. */
  reprend?: readonly string[];
  /** Nombre d’éléments du lot (pictos d’une même planche, déclinaisons…). */
  lot?: number;
  note?: string;
}

